library;

/// 一条更新记录
class ChangeEntry {
  const ChangeEntry({
    required this.version,
    required this.date,
    required this.summary,
    this.featuresTitle = '新增',
    this.fixes = const [],
    this.features = const [],
  });

  final String version;
  final String date;

  /// 一句话概括这一版在做什么
  final String summary;

  /// 「新增」那一段的小标题
  ///
  /// 第一版列的是整个软件能做什么，不是「这一版新增了什么」，
  /// 所以标题单独给得出来。
  final String featuresTitle;

  /// 修好的问题
  final List<String> fixes;

  /// 新增的功能
  final List<String> features;

  bool get isEmpty => fixes.isEmpty && features.isEmpty;
}

